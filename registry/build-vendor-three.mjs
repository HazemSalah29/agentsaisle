// Rebuilds registry/official/video-core/assets/vendor/three.mjs from the pinned `three` devDependency.
// Run by hand after changing registry/vendor/three-entry.mjs or the three version: node registry/build-vendor-three.mjs
// The output is committed (and not minified, so it reads as ordinary code), so installed skills never need npm
// or the network.
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { format } from "prettier";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const version = JSON.parse(
  readFileSync(path.join(root, "node_modules/three/package.json"), "utf8"),
).version;
const out = path.join(root, "registry/official/video-core/assets/vendor/three.mjs");

await build({
  entryPoints: [path.join(root, "registry/vendor/three-entry.mjs")],
  outfile: out,
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "chrome120",
  legalComments: "none",
  banner: {
    js: `// Bundled from three.js ${version} (MIT, https://github.com/mrdoob/three.js), only the classes the puppet scene uses.\n// Generated by registry/build-vendor-three.mjs; do not edit. Licences: see docs/video/THIRD_PARTY.md.`,
  },
});
// Lay the code out in normal line lengths (one very long array literal would read as packed code), and point
// documentation links in comments at https.
const laidOut = await format(readFileSync(out, "utf8"), { parser: "babel", printWidth: 100 });
// Shader sources come out of esbuild as one long string full of \n; put them back as multi-line template
// literals (the same text), so each shader line is one line of the file.
const asTemplate = (m) => {
  if (m.length < 200 || !m.includes("\\n")) return m;
  const text = JSON.parse(m.replaceAll("\t", "\\t"));
  return `\`${text.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${")}\``;
};
writeFileSync(
  out,
  laidOut
    .replace(/"(?:[^"\\\n]|\\.)*"/g, asTemplate)
    .split("\n")
    .map((l) => (/^\s*(\*|\/\/)/.test(l) ? l.replaceAll("http://", "https://") : l))
    .join("\n"),
);
console.log(`Wrote ${path.relative(root, out)} (three.js ${version})`);
