// Rebuilds registry/official/arch-visualize/assets/vendor/babel-parser.mjs from the pinned `@babel/parser` devDependency.
// Run by hand after changing the @babel/parser version: node registry/build-vendor-babel.mjs
// The output is committed, so installed skills never need npm or the network. It only parses text.
import { build } from "esbuild";
import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const version = JSON.parse(
  readFileSync(path.join(root, "node_modules/@babel/parser/package.json"), "utf8"),
).version;
const out = path.join(root, "registry/official/arch-visualize/assets/vendor/babel-parser.mjs");

await build({
  stdin: {
    contents: `export { parse } from "@babel/parser";`,
    resolveDir: root,
    sourcefile: "babel-parser-entry.mjs",
  },
  outfile: out,
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  legalComments: "none",
  banner: {
    js: `// Bundled from @babel/parser ${version} (MIT, https://github.com/babel/babel). Only \`parse\` is exported.\n// Generated by registry/build-vendor-babel.mjs; do not edit. It parses text and never runs it.`,
  },
});
console.log(`Wrote ${path.relative(root, out)} (@babel/parser ${version})`);
