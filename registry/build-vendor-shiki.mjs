// Rebuilds registry/official/video-core/assets/vendor/shiki.mjs from the pinned `shiki` devDependency.
// Run by hand after changing registry/vendor/shiki-entry.mjs or the shiki version: node registry/build-vendor-shiki.mjs
// The output is committed, so installed skills never need npm or the network.
import { build } from "esbuild";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const version = JSON.parse(
  readFileSync(path.join(root, "node_modules/shiki/package.json"), "utf8"),
).version;
const out = path.join(root, "registry/official/video-core/assets/vendor/shiki.mjs");

// Grammars and the theme go out as pretty-printed JSON, so the bundle itself is only code.
const dataDir = path.join(path.dirname(out), "shiki-data");
rmSync(dataDir, { recursive: true, force: true });
mkdirSync(dataDir, { recursive: true });
for (const [name, file] of [
  ...["javascript", "typescript", "json", "bash", "python"].map((n) => [n, `shiki/langs/${n}.mjs`]),
  ["github-dark", "shiki/themes/github-dark.mjs"],
]) {
  const mod = await import(file);
  writeFileSync(path.join(dataDir, `${name}.json`), `${JSON.stringify(mod.default, null, 1)}\n`);
}

await build({
  entryPoints: [path.join(root, "registry/vendor/shiki-entry.mjs")],
  outfile: out,
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  legalComments: "none",
  banner: {
    js: `// Bundled from Shiki ${version} (MIT, https://github.com/shikijs/shiki) with github-dark and 5 grammars (the data is in shiki-data/).\n// Generated by registry/build-vendor-shiki.mjs; do not edit. Licences: see docs/video/THIRD_PARTY.md.`,
  },
});
console.log(`Wrote ${path.relative(root, out)} (Shiki ${version})`);
